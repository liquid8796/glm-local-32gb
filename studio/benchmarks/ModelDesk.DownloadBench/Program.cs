using System.Diagnostics;
using System.Globalization;
using System.Net;
using System.Security.Cryptography;
using System.Text.Json;
using ModelDesk.Core;
using ModelDesk.Infrastructure.Downloads;

namespace ModelDesk.DownloadBench;

internal static class Program
{
    private const long MiB = 1024 * 1024;
    private const string Revision = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";

    public static async Task<int> Main(string[] args)
    {
        var sizeMiB = 64;
        var latency = 100;
        var connectionMiB = 8;
        string? output = null;
        for (var index = 0; index < args.Length; index++)
        {
            if (args[index] is "--help" or "-h")
            {
                Console.WriteLine("Local-only HTTP download benchmark: --size-mib 16..256 --latency-ms 0..1000 --connection-mib 1..128 [--output JSON_PATH]");
                return 0;
            }
            var option = args[index];
            if (++index >= args.Length) throw new ArgumentException("An option value is missing.");
            switch (option)
            {
                case "--size-mib": sizeMiB = Number(args[index], 16, 256); break;
                case "--latency-ms": latency = Number(args[index], 0, 1000); break;
                case "--connection-mib": connectionMiB = Number(args[index], 1, 128); break;
                case "--output": output = Path.GetFullPath(args[index]); break;
                default: throw new ArgumentException("Unknown benchmark option: " + option);
            }
        }
        using var stop = new CancellationTokenSource(TimeSpan.FromMinutes(5));
        Console.CancelKeyPress += (_, eventArgs) => { eventArgs.Cancel = true; stop.Cancel(); };
        var size = sizeMiB * MiB;
        var temporary = Path.Combine(Path.GetTempPath(), "ModelDesk.DownloadBench", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(temporary);
        try
        {
            var sha = LoopbackFileServer.ExpectedSha256(size);
            var baseline = await DownloadCase("one_connection", 1, Path.Combine(temporary, "one"), size, sha, connectionMiB * MiB, latency, stop.Token);
            var parallel = await DownloadCase("four_connections", 4, Path.Combine(temporary, "four"), size, sha, connectionMiB * MiB, latency, stop.Token);
            var resumed = await ResumeCase(Path.Combine(temporary, "resume"), size, sha, connectionMiB * MiB, latency, stop.Token);
            var report = new
            {
                status = "PASS",
                scope = "loopback_http_simulation",
                interpretation = "Local HTTP/process/disk measurements with an imposed per-connection server bandwidth limit. This is not an internet or Hugging Face speed measurement or guarantee.",
                server = new { bind = "127.0.0.1 only; ephemeral port", file_bytes = size, header_latency_ms = latency,
                    bytes_per_connection_second = connectionMiB * MiB, deterministic_body_buffer_bytes = 65536,
                    body = "bytes generated by absolute offset; no whole-file server buffer or file cache" },
                expected_sha256 = sha,
                cases = new[] { baseline, parallel },
                controlled_scenario_speedup = baseline.WallSeconds / parallel.WallSeconds,
                cancellation_resume = resumed,
                checked_at = DateTimeOffset.UtcNow
            };
            var json = JsonSerializer.Serialize(report, new JsonSerializerOptions { WriteIndented = true });
            Console.WriteLine(json);
            if (output is not null)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(output)!);
                await File.WriteAllTextAsync(output, json + Environment.NewLine, stop.Token);
            }
            return 0;
        }
        catch (Exception exception)
        {
            Console.Error.WriteLine(JsonSerializer.Serialize(new { status = "ERROR", error = exception.Message }));
            return exception is OperationCanceledException ? 130 : 1;
        }
        finally
        {
            // The only recursive cleanup target is the private fixture created
            // above. Check its absolute location before removing it on Windows.
            var parent = Path.GetFullPath(Path.Combine(Path.GetTempPath(), "ModelDesk.DownloadBench")) + Path.DirectorySeparatorChar;
            var target = Path.GetFullPath(temporary);
            if (!target.StartsWith(parent, StringComparison.OrdinalIgnoreCase)) throw new IOException("Benchmark cleanup escaped its fixture directory.");
            if (Directory.Exists(target)) Directory.Delete(target, recursive: true);
        }
    }

    private static async Task<CaseMeasurement> DownloadCase(string name, int connections, string folder, long size,
        string sha, long rate, int latency, CancellationToken cancellationToken)
    {
        await using var server = new LoopbackFileServer(size, rate, latency, sha);
        using var http = Client(server.Endpoint);
        var downloader = Downloader(http, connections, size);
        var request = Request(folder, size, sha);
        await downloader.ValidateBatchAsync([request], cancellationToken);
        var timer = Stopwatch.StartNew();
        var result = await downloader.DownloadAsync(request, cancellationToken: cancellationToken);
        timer.Stop();
        await server.WaitIdleAsync(cancellationToken);
        var checksum = await Checksum(result.FilePath, cancellationToken);
        if (!result.HashVerified || checksum != sha || new FileInfo(result.FilePath).Length != size) throw new InvalidDataException("Final download checksum or size failed.");
        var measurement = server.Snapshot();
        if (measurement.PeakDataConnections > connections || connections == 4 && measurement.PeakDataConnections < 2)
            throw new InvalidDataException("Observed HTTP concurrency does not match the requested benchmark path.");
        return new(name, connections, timer.Elapsed.TotalSeconds, size / (double)MiB / timer.Elapsed.TotalSeconds,
            size, measurement.BodyBytesWritten, measurement.PeakDataConnections, checksum, true, result.ResumedBytes,
            measurement.Requests);
    }

    private static async Task<object> ResumeCase(string folder, long size, string sha, long rate, int latency, CancellationToken cancellationToken)
    {
        await using var server = new LoopbackFileServer(size, rate, latency, sha);
        using var http = Client(server.Endpoint);
        var downloader = Downloader(http, 4, size);
        var request = Request(folder, size, sha);
        using var pause = CancellationTokenSource.CreateLinkedTokenSource(cancellationToken);
        long lastProgress = 0;
        var progress = new ProgressSink(value =>
        {
            Interlocked.Exchange(ref lastProgress, value.DownloadedBytes);
            if (value.DownloadedBytes >= size / 8) pause.Cancel();
        });
        var cancelled = false;
        var firstTimer = Stopwatch.StartNew();
        try { await downloader.DownloadAsync(request, progress, pause.Token); }
        catch (OperationCanceledException) when (pause.IsCancellationRequested) { cancelled = true; }
        firstTimer.Stop();
        if (!cancelled || File.Exists(Path.Combine(folder, "weights.bin"))) throw new InvalidDataException("Mid-transfer cancellation did not leave only a partial download.");
        await server.WaitIdleAsync(cancellationToken);
        var first = server.Snapshot();
        var resumeTimer = Stopwatch.StartNew();
        var result = await downloader.DownloadAsync(request, cancellationToken: cancellationToken);
        resumeTimer.Stop();
        await server.WaitIdleAsync(cancellationToken);
        var second = server.Snapshot();
        var resumedRequests = second.Requests.Skip(first.Requests.Count).ToArray();
        var requestedRemaining = resumedRequests.Where(value => value.Method == "GET" && value.End - value.Start + 1 > 1)
            .Sum(value => value.End - value.Start + 1);
        var checksum = await Checksum(result.FilePath, cancellationToken);
        if (result.ResumedBytes <= 0 || result.ResumedBytes >= size || checksum != sha || !result.HashVerified)
            throw new InvalidDataException("Resume did not preserve partial bytes and verify the final checksum.");
        if (result.ResumedBytes + requestedRemaining != size)
            throw new InvalidDataException("Resume range accounting does not equal the remaining file bytes.");
        return new
        {
            cancelled = true, cancel_after_reported_bytes = lastProgress, cancellation_wall_seconds = firstTimer.Elapsed.TotalSeconds,
            server_bytes_before_cancel_finished = first.BodyBytesWritten, persisted_resumed_bytes = result.ResumedBytes,
            requested_remaining_bytes = requestedRemaining, expected_file_bytes = size,
            resumed_plus_requested_equals_size = true,
            resume_server_body_bytes = second.BodyBytesWritten - first.BodyBytesWritten,
            resume_wall_seconds = resumeTimer.Elapsed.TotalSeconds,
            sha256 = checksum, hash_verified = true, peak_data_connections = second.PeakDataConnections,
            resume_requests = resumedRequests,
            accounting_note = "Server bytes count completed socket writes; cancellation can discard in-flight bytes. Persisted resumed bytes plus remaining requested ranges must equal file size. One-byte range probes are excluded from remaining-payload accounting."
        };
    }

    private static HttpClient Client(Uri endpoint) => new(new LoopbackTransport(endpoint,
        new SocketsHttpHandler { AllowAutoRedirect = false, AutomaticDecompression = DecompressionMethods.None,
            MaxConnectionsPerServer = 16, UseProxy = false })) { Timeout = Timeout.InfiniteTimeSpan };

    private static ModelDownloader Downloader(HttpClient http, int connections, long size)
    {
        var downloader = new ModelDownloader(http, new NoCredentials()) { BytesPerSecondLimit = 0 };
        var advanced = (IAdvancedDownloadOptions)downloader;
        advanced.ConnectionsPerFile = connections;
        advanced.ParallelThresholdBytes = Math.Min(64 * MiB, size);
        advanced.SegmentSizeBytes = Math.Max(MiB, size / 4);
        return downloader;
    }

    private static DownloadRequest Request(string folder, long size, string sha) =>
        new("benchmark/deterministic", Revision, new HubFile("weights.bin", size, sha), folder);

    private static async Task<string> Checksum(string path, CancellationToken cancellationToken)
    {
        await using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 65536,
            FileOptions.Asynchronous | FileOptions.SequentialScan);
        return Convert.ToHexString(await SHA256.HashDataAsync(stream, cancellationToken)).ToLowerInvariant();
    }

    private static int Number(string text, int min, int max) => int.TryParse(text, NumberStyles.Integer, CultureInfo.InvariantCulture, out var value)
        && value >= min && value <= max ? value : throw new ArgumentException($"Benchmark value must be {min}..{max}.");
    private sealed class NoCredentials : ICredentialStore
    {
        public Task<string?> GetTokenAsync(CancellationToken cancellationToken = default) => Task.FromResult<string?>(null);
        public Task SetTokenAsync(string? token, CancellationToken cancellationToken = default) => throw new NotSupportedException();
    }
    private sealed class ProgressSink(Action<DownloadProgress> report) : IProgress<DownloadProgress>
    { public void Report(DownloadProgress value) => report(value); }
}

internal sealed record CaseMeasurement(string Name, int ConnectionsPerFile, double WallSeconds, double MiBPerSecond,
    long ExpectedBytes, long ServerBodyBytesWritten, int PeakDataConnections, string Sha256, bool HashVerified,
    long ResumedBytes, IReadOnlyList<RequestMeasurement> Requests);

internal sealed class LoopbackTransport(Uri endpoint, HttpMessageHandler inner) : DelegatingHandler(inner)
{
    protected override async Task<HttpResponseMessage> SendAsync(HttpRequestMessage request, CancellationToken cancellationToken)
    {
        var original = request.RequestUri ?? throw new InvalidDataException("Missing benchmark request URI.");
        if (original.Scheme != "https" || original.Host != "huggingface.co")
            throw new InvalidDataException("Benchmark accepts only the downloader's standard Hub origin before local routing.");
        if (request.Headers.Authorization is not null) throw new InvalidDataException("Benchmark must not carry credentials.");
        try
        {
            request.RequestUri = new Uri(endpoint, original.PathAndQuery);
            var response = await base.SendAsync(request, cancellationToken);
            // Keep the production client's origin checks intact; only the test
            // transport rewrites the wire destination to the loopback listener.
            response.RequestMessage = request;
            return response;
        }
        finally { request.RequestUri = original; }
    }
}
